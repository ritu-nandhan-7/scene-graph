"""Build E2 references without initializing network-backed Python models.

The production/Pillow/OpenCLIP records come from the unchanged-production E1
reference run. Static detector references use the exact immutable 640-square
browser ONNX artifact through Python ONNX Runtime. All outputs stay isolated.
"""
from __future__ import annotations

import hashlib
import json
import platform
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

import cv2
import numpy as np
import onnxruntime
import PIL
import torch
import ultralytics
from PIL import Image
from ultralytics.utils import ops
from ultralytics.utils.nms import non_max_suppression

OUT = ROOT / "experiments" / "browser-feasibility" / "e2-preprocessing-parity"
PUBLIC = ROOT / "experiments" / "browser-feasibility" / "browser-yolo-test" / "public" / "e2"
E1 = ROOT / "experiments" / "browser-feasibility" / "browser-yolo-test" / "public" / "e1"
MODEL = ROOT / "experiments" / "browser-feasibility" / "browser-yolo-test" / "public" / "model" / "yolov8s-world-vg150-640-static-adaptive-max.onnx"
SAMPLES = ("fixture-1", "few-100", "moderate-107899", "many-107900", "overlap-107901")


def digest(value: np.ndarray) -> str:
    return hashlib.sha256(np.ascontiguousarray(value).tobytes()).hexdigest()


def write_json(path: Path, value: object) -> None:
    path.write_text(json.dumps(value, indent=2, sort_keys=True), encoding="utf-8")


def static_input(rgb: np.ndarray) -> tuple[np.ndarray, dict[str, int | float]]:
    height, width = rgb.shape[:2]
    ratio = min(640 / height, 640 / width)
    resized_width, resized_height = round(width * ratio), round(height * ratio)
    pad_width, pad_height = 640 - resized_width, 640 - resized_height
    left, top = round(pad_width / 2 - 0.1), round(pad_height / 2 - 0.1)
    bgr = np.ascontiguousarray(rgb[..., ::-1])
    resized = cv2.resize(bgr, (resized_width, resized_height), interpolation=cv2.INTER_LINEAR)
    boxed = cv2.copyMakeBorder(resized, top, pad_height - top, left, pad_width - left, cv2.BORDER_CONSTANT, value=(114, 114, 114))
    # Ultralytics converts BGR numpy input back to RGB internally before NCHW.
    tensor = np.ascontiguousarray(boxed[..., ::-1].transpose(2, 0, 1)[None], dtype=np.float32) / 255.0
    return tensor, {"ratio": ratio, "resized_width": resized_width, "resized_height": resized_height, "left": left, "top": top}


def decode(raw: np.ndarray, tensor: np.ndarray, rgb: np.ndarray, label_ids: dict[str, int], labels: list[str]) -> list[dict[str, object]]:
    prediction = torch.from_numpy(raw)
    selected = non_max_suppression(prediction, conf_thres=0.25, iou_thres=0.70, max_det=300)[0]
    if not len(selected):
        return []
    selected[:, :4] = ops.scale_boxes(tensor.shape[2:], selected[:, :4], rgb.shape[:2]).round()
    rows = []
    for index, row in enumerate(selected.cpu().numpy()):
        x1, y1, x2, y2, confidence, class_id = (float(value) for value in row)
        label = labels[int(class_id)]
        rows.append({"object_index": index, "label": label, "label_index": int(label_ids[label]), "confidence": confidence, "xyxy": [x1, y1, x2, y2], "bbox": {"cx": (x1 + x2) / 2, "cy": (y1 + y2) / 2, "width": x2 - x1, "height": y2 - y1}})
    return rows


def main() -> None:
    if not MODEL.is_file():
        raise FileNotFoundError(MODEL)
    e1_manifest = json.loads((E1 / "manifest.json").read_text(encoding="utf-8"))
    mappings = json.loads((E1 / "references" / "mappings.json").read_text(encoding="utf-8"))
    labels = json.loads((ROOT / "experiments" / "browser-feasibility" / "browser-yolo-test" / "public" / "references" / "vocabulary.json").read_text(encoding="utf-8"))
    labels = labels if isinstance(labels, list) else labels["vocabulary"]
    e1_by_id = {sample["id"]: sample for sample in e1_manifest["samples"]}
    if set(e1_by_id) != set(SAMPLES):
        raise RuntimeError("E1 fixtures do not match E2 fixtures")
    if PUBLIC.exists():
        shutil.rmtree(PUBLIC)
    refs = PUBLIC / "references"
    refs.mkdir(parents=True)
    session = onnxruntime.InferenceSession(str(MODEL), providers=["CPUExecutionProvider"])
    input_name, output_name = session.get_inputs()[0].name, session.get_outputs()[0].name
    manifest: dict[str, object] = {"contract": {"static_detector": "Pillow RGB pixels -> explicit OpenCV INTER_LINEAR BGR letterbox -> RGB NCHW / 255 -> immutable static browser ONNX", "production_reference": "Unchanged production SceneGraphPipeline records and Pillow/OpenCLIP tensors generated by E1.", "scope": "Static detector tensor/raw/detection parity plus production CLIP input preprocessing parity. Python E1 model-stage outputs remain the downstream reference."}, "environment": {"python": sys.version, "platform": platform.platform(), "opencv": cv2.__version__, "pillow": PIL.__version__, "torch": torch.__version__, "ultralytics": ultralytics.__version__, "onnxruntime": onnxruntime.__version__}, "samples": []}
    for sample in SAMPLES:
        e1_detail = json.loads((E1 / "references" / f"{sample}.json").read_text(encoding="utf-8"))
        source = ROOT / e1_detail["source_image"]
        with Image.open(source) as opened:
            orientation = opened.getexif().get(274)
            image = opened.convert("RGB")
        rgb = np.asarray(image, dtype=np.uint8).copy()
        tensor, letterbox = static_input(rgb)
        raw = session.run([output_name], {input_name: tensor})[0].astype(np.float32, copy=False)
        detections = decode(raw, tensor, rgb, mappings["label_name_to_vg_id"], labels)
        files = {"rgb": f"{sample}-rgb.npy", "yolo_input": f"{sample}-yolo-input.npy", "yolo_raw": f"{sample}-yolo-raw.npy", "clip_input": e1_detail["python_clip_input"]}
        np.save(refs / files["rgb"], rgb)
        np.save(refs / files["yolo_input"], tensor)
        np.save(refs / files["yolo_raw"], raw)
        shutil.copy2(E1 / "references" / files["clip_input"], refs / files["clip_input"])
        detail = {"id": sample, "category": e1_detail["category"], "source_image": e1_detail["source_image"], "decoded_image": {"width": image.width, "height": image.height, "mode": image.mode, "exif_orientation": orientation, "rgb_sha256": digest(rgb)}, "files": files, "arrays": {"rgb": {"shape": list(rgb.shape), "dtype": str(rgb.dtype), "sha256": digest(rgb)}, "yolo_input": {"shape": list(tensor.shape), "dtype": str(tensor.dtype), "sha256": digest(tensor)}, "yolo_raw": {"shape": list(raw.shape), "dtype": str(raw.dtype), "sha256": digest(raw)}}, "static_square_onnx_route": {"letterbox": letterbox, "detections": detections, "raw_shape": list(raw.shape)}, "production_rectangular_route": {"python_scene": e1_detail["python_scene"], "objects": e1_detail["python_objects_for_preprocess"], "pairs": e1_detail["python_pair_records"], "python_timings_seconds": e1_detail["python_timings_seconds"], "clip_tensor_source": "E1 unchanged-production Python OpenCLIP/Pillow reference"}}
        write_json(refs / f"{sample}.json", detail)
        manifest["samples"].append({"id": sample, "category": detail["category"], "reference": f"references/{sample}.json", "image": detail["decoded_image"], "static_detection_count": len(detections), "production_pair_count": e1_detail["directed_pair_count"]})
        print(f"{sample}: static={len(detections)} production_pairs={e1_detail['directed_pair_count']}", flush=True)
    write_json(PUBLIC / "manifest.json", manifest)
    OUT.mkdir(parents=True, exist_ok=True)
    write_json(OUT / "python-reference-manifest.json", manifest)


if __name__ == "__main__":
    main()
